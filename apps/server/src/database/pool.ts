import pg from "pg";

/**
 * Пул соединений с базой. Обрыв соединения – например, при перезапуске Postgres – соединение
 * сообщает событием `error`, и без обработчика оно роняет процесс. Запрос на оборванном
 * соединении получит ошибку сам, а пул выбросит соединение и к следующему запросу откроет новое.
 */
export function createPool(connectionString: string) {
  const pool = new pg.Pool({ connectionString });
  // Своё соединение без обработчика остаётся, пока его держат: миграции, транзакция better-auth.
  pool.on("connect", (client) => {
    client.on("error", (error) => {
      console.error(`Соединение с базой оборвалось: ${error.message}`);
    });
  });
  // Обрыв простаивающего соединения пул повторяет своим событием; записан он уже выше.
  pool.on("error", () => {});
  return pool;
}
