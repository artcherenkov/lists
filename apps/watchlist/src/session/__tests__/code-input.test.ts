import { describe, expect, test } from "vitest";

import { codeFromField, codeInText } from "../code-input.ts";

// Образец сообщения бота. Что разбор понимает настоящее сообщение, проверяет e2e входа: он
// вставляет в поле ответ бота целиком.
const BOT_MESSAGE = [
  "Код для входа в Lists: 48151623",
  "",
  "Введите его на v2.watchlist.acherenkov.com в течение 5 минут.",
  "Никому не сообщайте код: он впускает в ваш аккаунт.",
].join("\n");

describe("код во вставленном тексте", () => {
  test.each([
    ["код", "48151623", "48151623"],
    ["код с пробелом", "4815 1623", "48151623"],
    ["код с дефисом", "4815-1623", "48151623"],
    ["сообщение бота целиком", BOT_MESSAGE, "48151623"],
    [
      "сообщение бота, где поле заменило переводы строк пробелами",
      BOT_MESSAGE.replaceAll("\n", " "),
      "48151623",
    ],
    ["часть кода", "4815", undefined],
    ["лишняя цифра", "481516239", undefined],
    ["два кода", "48151623 и 00000000", undefined],
  ])("%s", (_case, text, code) => {
    expect(codeInText(text)).toBe(code);
  });
});

describe("код из поля после набора", () => {
  test.each([
    ["набранные цифры", "4815", "4815"],
    ["набранные цифры с пробелом", "4815 16", "481516"],
    ["пустое поле", "", ""],
    ["пробел после полного кода", "48151623 ", "48151623"],
    ["цифра после полного кода не принимается", "481516239", undefined],
    ["цифра в середине полного кода не принимается", "481591623", undefined],
    ["сообщение бота, подставленное после набранных цифр", `1234${BOT_MESSAGE}`, "48151623"],
    [
      "сообщение бота, подставленное к полному коду, не принимается",
      `00000000${BOT_MESSAGE}`,
      undefined,
    ],
  ])("%s", (_case, value, code) => {
    expect(codeFromField(value)).toBe(code);
  });
});
