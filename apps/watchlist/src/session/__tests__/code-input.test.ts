import { describe, expect, test } from "vitest";

import { codeFromInput } from "../code-input.ts";

// Сообщение бота, как его копирует Telegram (текст – `codeMessage` в apps/server/src/telegram/bot.ts).
const BOT_MESSAGE = [
  "Код для входа в Lists: 48151623",
  "",
  "Введите его на v2.watchlist.acherenkov.com в течение 5 минут.",
  "Никому не сообщайте код: он впускает в ваш аккаунт.",
].join("\n");

describe("код из поля ввода", () => {
  test.each([
    ["набранные цифры", "4815", "4815"],
    ["полный код", "48151623", "48151623"],
    ["код с пробелом", "4815 1623", "48151623"],
    ["код с дефисом", "4815-1623", "48151623"],
    ["сообщение бота целиком", BOT_MESSAGE, "48151623"],
    ["новый код, вставленный в поле с прежним", "1234567848151623", "48151623"],
    ["сообщение бота, вставленное в поле с прежним кодом", `12345678${BOT_MESSAGE}`, "48151623"],
    ["лишняя цифра в конце", "481516239", "81516239"],
    ["ни одной цифры", "код", ""],
  ])("%s", (_case, input, code) => {
    expect(codeFromInput(input)).toBe(code);
  });
});
