import { describe, expect, test } from "vitest";

import { codeFromInput } from "../code-input.ts";

// Образец сообщения бота. Что разбор понимает настоящее сообщение, проверяет e2e входа: он
// вставляет в поле ответ бота целиком.
const BOT_MESSAGE = [
  "Код для входа в Lists: 48151623",
  "",
  "Введите его на v2.watchlist.acherenkov.com в течение 5 минут.",
  "Никому не сообщайте код: он впускает в ваш аккаунт.",
].join("\n");

describe("код из поля ввода", () => {
  test.each([
    ["набранные цифры", "4815", "481", "4815"],
    ["последняя цифра кода", "48151623", "4815162", "48151623"],
    ["стёртая цифра полного кода", "4815162", "48151623", "4815162"],
    ["код с пробелом", "4815 1623", "", "48151623"],
    ["код с дефисом", "4815-1623", "", "48151623"],
    ["сообщение бота целиком", BOT_MESSAGE, "", "48151623"],
    ["сообщение бота, вставленное после набранных цифр", `4815${BOT_MESSAGE}`, "4815", "48151623"],
    ["новый код, вставленный после прежнего", "0000000048151623", "00000000", "48151623"],
    ["новый код, вставленный перед прежним", "4815162300000000", "00000000", "48151623"],
    [
      "сообщение бота, вставленное перед прежним кодом",
      `${BOT_MESSAGE}00000000`,
      "00000000",
      "48151623",
    ],
    ["тот же код, вставленный снова", "4815162348151623", "48151623", "48151623"],
    ["цифра, набранная после полного кода, начинает новый", "481516239", "48151623", "9"],
    ["лишние цифры при наборе отбрасываются", "481516239", "", "48151623"],
    ["ни одной цифры", "код", "", ""],
  ])("%s", (_case, input, previous, code) => {
    expect(codeFromInput(input, previous)).toBe(code);
  });
});
